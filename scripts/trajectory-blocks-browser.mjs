import assert from 'node:assert/strict';
import { join } from 'node:path';
export async function runOutputBlocksCase(page, artifacts) {
  await page.getByRole('tab', { name: '轨迹', exact: true }).evaluate(node => node.click());
  const controls = page.locator('[data-trajectory-accessibility="controls"]');
  const tabs = page.getByRole('tablist', { name: '事件详情', exact: true });
  const output = page.locator('.trajectory-json-frame:not([hidden])[data-trajectory-kind="tool-output"]');
  const select = async name => {
    const row = controls.getByRole('button', { name: new RegExp(`^#\\d+ 工具 ${name} `) });
    await row.waitFor(); await row.evaluate(node => node.click());
    await tabs.getByRole('tab', { name: '结果', exact: true }).evaluate(node => node.click());
    await output.waitFor();
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  };
  await select('json_single');
  await output.getByRole('tree', { name: '结果 JSON' }).waitFor();
  await select('json_split');
  await output.locator('pre').filter({ hasText: '{"a":' }).waitFor();
  assert.deepEqual(await output.locator('pre').allTextContents(), ['{"a":', '1}']);
  assert.equal(await output.getByRole('tree').count(), 0, 'separate blocks must not become a synthetic JSON object');
  await select('mixed_image');
  const image = output.getByRole('button', { name: 'fixture.png，点击查看原图', exact: true });
  await image.waitFor();
  await page.waitForFunction(() => document.querySelector('[data-trajectory-kind="tool-output"] img')?.complete);
  assert.deepEqual(await output.locator('.trajectory-tool-text-output').evaluate(node => [...node.children].map(child => child.tagName)), ['PRE','DIV','PRE']);
  assert.deepEqual(await output.locator('pre').allTextContents(), ['before <b>literal</b>', 'after\n']);
  assert.equal(await output.locator('pre b').count(), 0);
  assert.equal(await output.locator('.trajectory-tool-text-output').evaluate(node => getComputedStyle(node).gap), '10px');
  assert.deepEqual(await image.evaluate(node => ({width:node.getBoundingClientRect().width,height:node.getBoundingClientRect().height})), {width:64,height:64});
  await image.click();
  const lightbox = page.getByRole('dialog', { name: '原图预览', exact: true });
  await lightbox.waitFor();
  await page.screenshot({ path: join(artifacts, 'tool-image-lightbox.png') });
  await page.keyboard.press('Escape');
  await lightbox.waitFor({state:'detached'});
  // The AX tablist has fixed-position children and no layout box of its own.
  assert.equal(await tabs.getByRole('tab', { name: '结果', exact: true }).isVisible(), true, 'Escape closes only the original image');
  assert.equal(await image.evaluate(node=>node===document.activeElement), true);
  await image.press('Shift+F10');
  await page.getByRole('menuitem',{name:'下载',exact:true}).click();
  await page.waitForFunction(()=>window.__verification.calls.some(call=>call.name==='save_image_attachment'&&call.args.mode==='download'));
  await image.click({button:'right'});
  await page.getByRole('menuitem',{name:'另存为…',exact:true}).click();
  await page.waitForFunction(()=>window.__verification.calls.some(call=>call.name==='save_image_attachment'&&call.args.mode==='saveAs'));
  const saved=await page.evaluate(()=>window.__verification.calls.filter(call=>call.name==='save_image_attachment').map(call=>call.args));
  assert.equal(saved.length,2); assert.equal(saved[0].attachmentId,`sha256:${'a'.repeat(64)}`); assert.equal(saved[0].name,'fixture.png');
  await page.context().grantPermissions(['clipboard-read','clipboard-write']);
  await image.click({button:'right'});
  await page.getByRole('menuitem',{name:'复制图片',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'已复制'}).waitFor();
  assert.ok(await page.evaluate(async()=>(await navigator.clipboard.read()).some(item=>item.types.includes('image/png'))));
  await tabs.getByRole('tab',{name:'概述',exact:true}).evaluate(node=>node.click());
  await output.locator('.trajectory-tool-output-preview').waitFor();
  await output.locator('.trajectory-tool-text-output:not(.trajectory-tool-output-preview)').waitFor({state:'detached'});
  assert.equal(await output.locator('.trajectory-tool-text-output').evaluate(node=>getComputedStyle(node).gap),'6px');
  await page.screenshot({path:join(artifacts,'tool-blocks-overview.png')});
  await select('error_image');
  const retry=output.getByRole('button',{name:'图片加载失败，点击重试',exact:true});
  await retry.waitFor();
  await output.locator('pre').getByText('ToolError: E_IMAGE',{exact:true}).waitFor();
  const failedReads=await page.evaluate(()=>{
    window.__verification.imageAvailable=true;
    return window.__verification.calls.filter(call=>call.name==='read_attachment'&&call.args.attachmentId==='b'.repeat(64)).length;
  });
  await retry.click();
  await output.getByRole('button',{name:'retry.png，点击查看原图',exact:true}).locator('img').waitFor();
  assert.equal(await page.evaluate(()=>window.__verification.calls.filter(call=>call.name==='read_attachment'&&call.args.attachmentId==='b'.repeat(64)).length),failedReads+1);
  await select('file_result');
  await output.locator('pre').filter({hasText:'report.txt'}).waitFor();
  assert.equal(await output.locator('img').count(),0,'ordinary files are not sent to the image loader');
  await page.setViewportSize({width:620,height:820});
  await select('mixed_image');
  await output.getByRole('button',{name:'fixture.png，点击查看原图',exact:true}).waitFor();
  await page.screenshot({path:join(artifacts,'tool-blocks-narrow.png')});
  await page.setViewportSize({width:1440,height:1100});
  const thumbnail=output.locator('img');
  await thumbnail.hover();
  const transfer=await page.evaluateHandle(()=>new DataTransfer());
  await page.waitForFunction(() => document.querySelector('[data-trajectory-kind="tool-output"] img')?.complete);
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  await thumbnail.dispatchEvent('dragstart',{dataTransfer:transfer});
  assert.equal(await transfer.evaluate(data=>data.types.includes('application/x-dsh-file')),true,'upstream drag carries an owned file token');
  await page.evaluate(data=>{
    window.dispatchEvent(new DragEvent('dragenter',{dataTransfer:data,bubbles:true,cancelable:true}));
    window.dispatchEvent(new DragEvent('drop',{dataTransfer:data,bubbles:true,cancelable:true}));
  },transfer);
  await page.getByRole('group',{name:'草稿附件'}).getByRole('button',{name:/fixture.png/}).waitFor();
  await transfer.dispose();
}
